ROOT = Path(__file__).resolve().parents[1]
README_START = "<!-- RESULTS-TABLE:START -->"
README_END = "<!-- RESULTS-TABLE:END -->"
ZOOMS = {
    "2008: Lehman and after": ("2008-06-01", "2009-06-30"),
    "March 2020: COVID crash": ("2020-02-01", "2020-06-30"),
    "2022: rates shock": ("2022-01-01", "2022-12-31"),
}


def log(msg: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def save_forecasts(results: dict[str, ForecastResult], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for name, res in results.items():
        slug = name.lower().replace(" ", "_").replace("-", "_")
        res.frame.to_csv(out / f"{slug}.csv", float_format="%.8g")


def fmt_p(p: float) -> str:
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def markdown_final_table(final: pd.DataFrame, es_level: float) -> str:
    """Final table in Markdown: method x level x exception rate x p-values x zone."""
    lines = [
        "| Method | Level | Exceptions (expected) | Rate | Kupiec p | Christoffersen IND p "
        "| CC p | Z2 (p) | Worst zone | Days in red |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for _, r in final.iterrows():
        z2 = f"{r['Z2']:.3f} ({fmt_p(r['p_Z2'])})" if np.isclose(r["level"], es_level) else "—"
        lines.append(
            f"| {r['model']} | {100 * r['level']:g} % | {int(r['N'])} ({r['expected']:.1f}) "
            f"| {r['rate']:.2%} | {fmt_p(r['p_uc'])} | {fmt_p(r['p_ind'])} | {fmt_p(r['p_cc'])} "
            f"| {z2} | {r['worst_zone']} | {r['share_red']:.1%} |"
        )
    return "\n".join(lines)


def update_readme(table_md: str, cfg: Config, period: str) -> None:
    readme = ROOT / "README.md"
    if not readme.exists():
        log("README.md not found: table not inserted")
        return
    text = readme.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        log("README markers not found: table not inserted")
        return
    head, rest = text.split(README_START, 1)
    _, tail = rest.split(README_END, 1)
    note = (
        f"*{period}; estimation window W = {cfg.window} days; Z2 at "
        f"{100 * cfg.es_level:g} % with {cfg.z2_sims:,} simulations under each model's own "
        "predictive distribution. Zones: Basel (1996) at 99 %; at 97.5 % the same binomial "
        "thresholds (Basel-equivalent, non-regulatory). Generated by `scripts/run_results.py`.*"
    )
    block = f"{README_START}\n{table_md}\n\n{note}\n{README_END}"
    readme.write_text(head + block + tail, encoding="utf-8")
    log("README results table updated")


def mc_noise(R: pd.DataFrame, cfg: Config, dates: list[str], n_seeds: int = 20) -> pd.DataFrame:
    """Dispersion of Monte Carlo VaR / ES across seeds, at given forecast dates."""
    rows = []
    for d in dates:
        i = int(R.index.get_indexer([pd.Timestamp(d)], method="bfill")[0])
        hist = R.to_numpy()[:i]
        base = MonteCarloCopula(cfg.weight_vector, cfg.window, n_sims=cfg.mc_sims, seed=0)
        nus = base.fit(hist)
        for lv in cfg.levels:
            v, e = [], []
            for s in range(n_seeds):
                m = MonteCarloCopula(cfg.weight_vector, cfg.window, n_sims=cfg.mc_sims, seed=s)
                p = m.predict(hist, nus)
                v.append(p.var(lv))
                e.append(p.es(lv))
            rows.append(
                {
                    "date": R.index[i].date().isoformat(),
                    "level": lv,
                    "n_sims": cfg.mc_sims,
                    "VaR_mean": np.mean(v),
                    "VaR_sd": np.std(v, ddof=1),
                    "VaR_rel_sd": np.std(v, ddof=1) / np.mean(v),
                    "ES_mean": np.mean(e),
                    "ES_sd": np.std(e, ddof=1),
                    "ES_rel_sd": np.std(e, ddof=1) / np.mean(e),
                }
            )
    return pd.DataFrame(rows)


def data_summary(R: pd.DataFrame, cfg: Config, first_forecast: pd.Timestamp) -> dict[str, object]:
    r = portfolio_returns(R, cfg.weight_vector)
    t_fit = fit_student_t(r.to_numpy(), cfg.nu_bounds)
    g = fit_garch11(r.to_numpy())
    corr = R["SPY"].rolling(250).corr(R["TLT"])
    return {
        "first_return_date": R.index[0].date().isoformat(),
        "last_date": R.index[-1].date().isoformat(),
        "n_returns": len(R),
        "first_forecast_date": first_forecast.date().isoformat(),
        "annualised_mean_simple": float(r.mean() * 252),
        "annualised_vol": float(r.std(ddof=1) * np.sqrt(252)),
        "worst_day": r.idxmin().date().isoformat(),
        "worst_day_return": float(r.min()),
        "full_sample_t_nu": t_fit.nu,
        "full_sample_garch_alpha_plus_beta": g.persistence,
        "full_sample_garch_half_life_days": float(np.log(0.5) / np.log(g.persistence)),
        "spy_tlt_corr_250d_mean_2007_2021": float(corr.loc["2007":"2021"].mean()),
        "spy_tlt_corr_250d_end_2022": float(corr.loc["2022"].iloc[-1]),
    }


def tables_for(results: dict[str, ForecastResult], cfg: Config) -> dict[str, pd.DataFrame]:
    cov = A.coverage_table(results, cfg.levels)
    zone_sum = pd.concat(
        [
            A.zone_summary(A.zones_by_model(results, lv, cfg.zone_window), lv, cfg.zone_window)
            for lv in cfg.levels
        ],
        ignore_index=True,
    )
    es = A.es_backtest_table(results, cfg.es_level, cfg.crisis_windows)
    final = A.final_table(cov, es, zone_sum, cfg.es_level)
    return {"coverage": cov, "zones": zone_sum, "es": es, "final": final}


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--skip-sensitivity",
        action="store_true",
        help="do not re-run the study with a 250-day window",
    )
    ap.add_argument("--data-dir", type=Path, default=ROOT / "data")
    ap.add_argument(
        "--readme-only",
        action="store_true",
        help="only re-insert results/final_table.md into README.md",
    )
    args = ap.parse_args()
    if args.readme_only:
        info = json.loads((ROOT / "results" / "run_info.json").read_text())
        table = (ROOT / "results" / "final_table.md").read_text(encoding="utf-8").strip()
        update_readme(table, Config(), info["period"])
        return

    t_start = time.time()
    cfg = Config()
    res_dir, fig_dir = ROOT / "results", ROOT / "figures"
    res_dir.mkdir(exist_ok=True)
    fig_dir.mkdir(exist_ok=True)

    prices = load_prices(args.data_dir, cfg.tickers)  # verifies SHA-256 against the manifest
    R = simple_returns(prices)
    log(f"data: {len(R)} daily returns {R.index[0].date()} -> {R.index[-1].date()}")

    results = run_all(R, cfg, log=log)
    save_forecasts(results, res_dir / "forecasts")
    first = next(iter(results.values())).frame.index[0]
    last = next(iter(results.values())).frame.index[-1]
    period = f"Out-of-sample {first.date()} to {last.date()} ({len(R) - cfg.window:,} days)"

    t = tables_for(results, cfg)
    t["coverage"].to_csv(res_dir / "coverage_tests.csv", index=False, float_format="%.6g")
    t["zones"].to_csv(res_dir / "traffic_light_summary.csv", index=False, float_format="%.6g")
    t["es"].to_csv(res_dir / "es_backtest.csv", index=False, float_format="%.6g")
    t["final"].to_csv(res_dir / "final_table.csv", index=False, float_format="%.6g")
    table_md = markdown_final_table(t["final"], cfg.es_level)
    (res_dir / "final_table.md").write_text(table_md + "\n", encoding="utf-8")

    crisis = A.crisis_table(results, cfg.levels, cfg.crisis_windows, cfg.zone_window)
    crisis.to_csv(res_dir / "crisis_breakdown.csv", index=False, float_format="%.6g")
    clus = A.clustering_table(results, cfg.levels, horizon=10)
    clus.to_csv(res_dir / "clustering.csv", index=False, float_format="%.6g")
    capital = A.capital_table(results, cfg.crisis_windows, cfg.zone_window)
    capital.to_csv(res_dir / "capital_charge.csv", index=False, float_format="%.6g")
    for lv in cfg.levels:
        A.exceptions_by_year(results, lv).to_csv(
            res_dir / f"exceptions_by_year_{100 * lv:g}.csv", float_format="%.6g"
        )
    zones99 = A.zones_by_model(results, 0.99, cfg.zone_window)
    pd.DataFrame({m: z["count"] for m, z in zones99.items()}).to_csv(
        res_dir / "rolling_exception_count_99.csv"
    )
    log("tables written")

    fig = plot_traffic_light(zones99, ZOOMS, 0.99, zone_bounds(cfg.zone_window, 0.01))
    fig.savefig(fig_dir / "traffic_light.png", dpi=150)
    fig = plot_var_paths(results, ["Historical", "FHS-GARCH"], 0.99, ZOOMS)
    fig.savefig(fig_dir / "var_paths.png", dpi=150)
    fig = plot_clustering(clus, cfg.levels, horizon=10)
    fig.savefig(fig_dir / "clustering.png", dpi=150)
    log("figures written")

    noise = mc_noise(R, cfg, ["2008-10-15", "2020-03-16", "2022-06-13"])
    noise.to_csv(res_dir / "mc_noise.csv", index=False, float_format="%.6g")
    summary = data_summary(R, cfg, first)
    (res_dir / "data_summary.json").write_text(json.dumps(summary, indent=2))
    log("Monte Carlo noise and data summary written")

    if not args.skip_sensitivity:
        cfg250 = replace(cfg, window=250)
        res250 = run_all(R, cfg250, log=log)
        t250 = tables_for(res250, cfg250)
        t250["final"].assign(window=250).to_csv(
            res_dir / "sensitivity_window250.csv", index=False, float_format="%.6g"
        )
        A.crisis_table(res250, cfg.levels, cfg.crisis_windows, cfg.zone_window).to_csv(
            res_dir / "sensitivity_window250_crisis.csv", index=False, float_format="%.6g"
        )
        log("sensitivity (W = 250) written")

    update_readme(table_md, cfg, period)

    manifest = json.loads((args.data_dir / MANIFEST_FILE).read_text())
    run_info = {
        "package_version": __version__,
        "period": period,
        "config": {k: v for k, v in asdict(cfg).items()},
        "data_sha256": manifest["sha256"],
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "runtime_seconds": round(time.time() - t_start, 1),
        "model_seconds": {m: round(r.seconds, 1) for m, r in results.items()},
        "fhs_garch_nonconverged_refits": int(
            (results["FHS-GARCH"].frame["garch_converged"].iloc[:: cfg.refit_every] == 0).sum()
        ),
        "forecast_columns": [var_col(lv) for lv in cfg.levels] + [es_col(lv) for lv in cfg.levels],
    }
    (res_dir / "run_info.json").write_text(json.dumps(run_info, indent=2, default=str))
    log(f"done in {time.time() - t_start:.0f} s")


if __name__ == "__main__":
    main()
