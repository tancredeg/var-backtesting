"""Regenerate every table and figure of the README from the frozen data snapshot.

Usage
-----
    python scripts/run_results.py                      # full run (~8 min on a laptop)
    python scripts/run_results.py --skip-sensitivity   # main specification only (~4 min)

Outputs
-------
results/*.csv, results/final_table.md, results/run_info.json, figures/*.png, and the
results table of README.md (between the RESULTS-TABLE markers) — rewritten in place so that
the README cannot drift from the code.
"""

